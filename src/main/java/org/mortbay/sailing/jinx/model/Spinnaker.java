package org.mortbay.sailing.jinx.model;

/**
 * A boat's spinnaker designation. Display-only — the Jinx handicap does not
 * treat spinnaker and non-spinnaker boats differently; the TCF absorbs the
 * difference like it absorbs everything else.
 */
public enum Spinnaker
{
    /** Spinnaker. */
    S,
    /** Non-spinnaker. */
    NS
}
